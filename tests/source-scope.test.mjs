test('reviewed annual windows update both planning and child calendars only from their effective date',async()=>{
  let data=null,content='Pierwotna treść. ';
  const monitor=createMonitor({catalog,clock,store:{read:async()=>structuredClone(data),write:async s=>{data=structuredClone(s);}},fetcher:async()=>new Response('<main>'+content.repeat(40)+'</main>',{headers:{'Content-Type':'text/html'}})});
  await monitor.refresh();content='Zmieniona treść. ';await monitor.refresh();
  const patch={id:'800-renewal',description:'Zweryfikowany opis nowego okresu corocznego z oficjalnego źródła.',end:{anchor:'birth',months:12},validFrom:'2027-01-01',calendarWindow:{start:'03-01',end:'07-15'}};
  await assert.rejects(()=>monitor.review({sourceId:'800',hash:data.sources['800'].pending.hash,patches:[{...patch,calendarWindow:{start:'02-30',end:'07-15'}}]}));
  await monitor.review({sourceId:'800',hash:data.sources['800'].pending.hash,patches:[patch]});
  const planning={mode:'pregnancy',anchor:'2026-11-21',planning:true};
  assert.equal(datedEvents(data.catalog,planning,'2026-12-01').find(e=>e.id==='planning-800-cycle').start,'2026-02-01');
  const future=datedEvents(data.catalog,planning,'2027-02-01').find(e=>e.id==='planning-800-cycle');
  assert.equal(future.start,'2027-03-01');assert.equal(future.end,'2027-07-15');assert.match(future.description,/Zweryfikowany opis/);
  const child=datedEvents(data.catalog,{mode:'child',anchor:'2026-11-21'},'2027-02-01').find(e=>e.id==='800-renewal');
  assert.equal(child.start,'2027-03-01');assert.equal(child.end,'2027-07-15');
});
